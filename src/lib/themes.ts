import type { ITheme } from '@xterm/xterm';

export interface Theme {
  id: string;
  name: string;
  /** CSS custom properties for the UI. */
  ui: Record<string, string>;
  terminal: ITheme;
}

function ui(
  bg: string,
  panel: string,
  input: string,
  border: string,
  text: string,
  dim: string,
  accent: string,
  scheme: 'dark' | 'light',
): Record<string, string> {
  return {
    '--bg': bg,
    '--bg-panel': panel,
    '--bg-input': input,
    '--bg-hover': `color-mix(in srgb, ${text} 8%, transparent)`,
    '--bg-active': `color-mix(in srgb, ${accent} 22%, transparent)`,
    '--border': border,
    '--text': text,
    '--text-dim': dim,
    '--accent': accent,
    '--color-scheme': scheme,
  };
}

